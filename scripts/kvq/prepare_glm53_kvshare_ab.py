def render_gpu13(pool=False):
    """Arm D of the 2026-10-08 online test: gpu13's two long-context GLM replicas (r1a GPUs 4-5,
    r1b GPUs 6-7) share one L3 HiCache file store on the `kvshare2` tmpfs. RAM-neutral:
    2 x 250 GiB L2 + 150 GiB store = 2 x 325 GiB. Every other service in small-models.yaml is
    byte-identical; deploy only r1a/r1b with a scoped compose/up."""
    src = (ROOT / SOURCE13).read_text()
    patch = (ROOT / PATCH).read_text()
    l2, store, cap, tmpfs = ("64GiB", "520GiB", "208Gi", "540g") if pool else ("250GiB", "150GiB", "60Gi", "160g")
    suffix = "-kvsharepool-v1" if pool else D_SUFFIX
    budget_note = ("64 GiB private L2 (staging) + half of the 520 GiB shared L3 store = 325 GiB" if pool
                   else "250 GiB L2 + half of the 150 GiB shared L3 store = 325 GiB")
    out = ("# GENERATED by scripts/kvq/prepare_glm53_kvshare_ab.py --gpu13 from " + str(SOURCE13) + " -- do not edit by hand.\n"
           + (("# ONLINE TEST ARM D' (exp 32): model-sg-glm53-w4afp8-tp2-r1a + r1b pool their host cache: 64 GiB private L2\n"
            "# each (staging) + one 520 GiB shared L3 store on `kvshare2` = 2 x 325 GiB (startup patch glm53_shared_kv).\n") if pool else
           ("# ONLINE TEST ARM D: model-sg-glm53-w4afp8-tp2-r1a + r1b share an L3 HiCache file tier on the `kvshare2`\n"
           "# tmpfs volume (startup patch glm53_shared_kv_startup_patch, 2 x 250 GiB L2 + 150 GiB store = 2 x 325 GiB).\n"))
           + "# Every other service is unchanged. Plan: tee-bench exp 31. Deploy only r1a/r1b, one at a time, scoped.\n") + src

    def argv_of(block_start, indent):
        start = out.index(" " * indent + "command: >\n", block_start)
        lines = out[start:].split("\n")[1:]
        argv = []
        for l in lines:
            if not l.startswith(" " * (indent + 2)) or not l.strip():
                break
            argv.append(l.strip())
        assert argv[0] == "sglang serve" and "--enable-hierarchical-cache" in argv, argv[:3]
        end = start + len(" " * indent + "command: >\n") + sum(len(l) + 1 for l in lines[:len(argv)])
        return " ".join(argv), start, end

    def kv_block(argv, pad):
        p = " " * pad
        return (f"{p}# Arm D: launched through the shared-KV startup patch (fail closed), plus the L3 file tier\n"
                f"{p}# on the `kvshare2` tmpfs both GLM replicas mount.\n"
                f"{p}entrypoint: [\"bash\", \"-c\"]\n"
                f"{p}command:\n{p}  - |\n{p}    python3 /etc/glm53/shared_kv_patch.py || exit 1\n"
                f"{p}    exec {argv} {SHARED_ARGS}\n"
                f"{p}configs:\n{p}  - source: glm53_shared_kv_patch\n{p}    target: /etc/glm53/shared_kv_patch.py\n{p}    mode: 0444\n"
                f"{p}volumes:\n{p}  - kernel_cache:/root/.cache\n{p}  - hugginface_cache:/root/.cache/huggingface\n"
                f"{p}  - ghost:/ghost\n{p}  - kvshare2:/kvshared\n")

    def tier_env(pad):
        p = " " * pad
        return "".join(p + l + "\n" for l in [
            "# Shared L3 tier (arm D). The store is the `kvshare2` tmpfs both GLM replicas mount; each",
            "# replica's evictor is capped at MAX_SIZE (non-owner TP ranks at 0.25x for their own mamba",
            ("# shards), and 2 x 1.25 x 208Gi = 520Gi = the store budget." if pool else "# shards), and 2 x 1.25 x 60Gi = 150Gi = the store budget."),
            "- SGLANG_HICACHE_FILE_BACKEND_STORAGE_DIR=/kvshared",
            "- SGLANG_HICACHE_FILE_BACKEND_ENABLE_METADATA_CACHE=1",
            f"- SGLANG_HICACHE_FILE_BACKEND_MAX_SIZE=${{GLM53_KVSHARE_FILE_MAX:-{cap}}}",
            f"- SGLANG_HICACHE_SHARED_STORE_BUDGET=${{GLM53_KVSHARE_STORE_BUDGET:-{store}}}",
            "- SGLANG_KVSHARE_METRICS=1",
            "# One INFO line per storage restore (pages, MB, s, MB/s).",
            "- SGLANG_KVSHARE_LOG_READS=1"])

    # r1b first (its own command and environment), then r1a (anchor argv; body gets the block).
    b0 = out.index("  model-sg-glm53-w4afp8-tp2-r1b:\n")
    assert "\n    configs:" not in out[b0:out.index("\n  glm53-ghost-aggregator:", b0)]
    argv_b, cs, ce = argv_of(b0, 4)
    out = out[:cs] + kv_block(argv_b, 4) + out[ce:]
    out = one(out, "      - SGLANG_HICACHE_RAM_BUDGET=${GLM53_R1B_HICACHE_RAM_BUDGET:-325GiB}\n",
              f"      # Arm D: {budget_note}.\n"
              f"      - SGLANG_HICACHE_RAM_BUDGET=${{GLM53_KVSHARE_RAM_BUDGET:-{l2}}}\n", "r1b ram budget")
    out = one(out, "      - SGLANG_GHOST_CACHE_REPLICA=r1b\n      - SGLANG_KV_TIER_METRICS=1\n",
              "      - SGLANG_GHOST_CACHE_REPLICA=r1b\n      - SGLANG_KV_TIER_METRICS=1\n" + tier_env(6), "r1b tier env")
    a_anchor = out.index("x-sg-glm53-flash-common: &sg-glm53-flash-common\n")
    argv_a, _, _ = argv_of(a_anchor, 2)
    a0 = out.index("  model-sg-glm53-w4afp8-tp2-r1a:\n")
    cn = "    container_name: model-sg-glm53-w4afp8-tp2-r1a\n"
    i = out.index(cn, a0) + len(cn)
    out = out[:i] + kv_block(argv_a, 4) + out[i:]
    # r1a has no environment of its own: it inherits the GLM anchor's (written for r1a); r1b
    # overrides it, and no other service uses that anchor.
    assert out.count("<<: *sg-glm53-flash-common") == 2
    out = one(out, "    - SGLANG_HICACHE_RAM_BUDGET=${GLM53_R1A_HICACHE_RAM_BUDGET:-325GiB}\n",
              f"    # Arm D (r1a inherits this list): {budget_note}.\n"
              f"    - SGLANG_HICACHE_RAM_BUDGET=${{GLM53_KVSHARE_RAM_BUDGET:-{l2}}}\n", "r1a ram budget")
    out = one(out, "    - SGLANG_GHOST_CACHE_REPLICA=r1a\n    - SGLANG_KV_TIER_METRICS=1\n",
              "    - SGLANG_GHOST_CACHE_REPLICA=r1a\n    - SGLANG_KV_TIER_METRICS=1\n" + tier_env(4), "r1a tier env")
    for r in ("r1a", "r1b"):
        s0 = out.index(f"  model-sg-glm53-w4afp8-tp2-{r}:\n")
        s1 = out.index("\n  model-sg-glm53-w4afp8-tp2-r1b:", s0) if r == "r1a" else out.index("\n  glm53-ghost-aggregator:", s0)
        body = out[s0:s1]
        body, n1 = re.subn(r'("config_variant:[^",]+)"', lambda m: m.group(1) + suffix + '"', body)
        body, n2 = re.subn(r'(nearai\.otel\.config_variant: "[^"]+)"', lambda m: m.group(1) + suffix + '"', body)
        assert (n1, n2) == (1, 1), (r, n1, n2)
        out = out[:s0] + body + out[s1:]
    out = one(out, '  ghost:\n    driver: local\n    driver_opts:\n      type: tmpfs\n      device: tmpfs\n      o: "size=1m,mode=0700"\n',
              '  ghost:\n    driver: local\n    driver_opts:\n      type: tmpfs\n      device: tmpfs\n      o: "size=1m,mode=0700"\n'
              f"  # Shared L3 HiCache store for the two GLM replicas only (arm D). Sized above the {store.replace('GiB', ' GiB')}\n"
              "  # store budget so the evictors, not tmpfs, bound it.\n"
              "  kvshare2:\n    driver: local\n    driver_opts:\n      type: tmpfs\n      device: tmpfs\n"
              f'      o: "size=${{GLM53_KVSHARE_TMPFS:-{tmpfs}}},mode=0700"\n', "kvshare2 volume")
    out = one(out, "\nconfigs:\n", "\nconfigs:\n  glm53_shared_kv_patch:\n    content: |\n" + block(patch, 6) + "\n\n", "configs block")
    return out



