def render_hicache_off(replicas):
    """Arm B of the 2026-10-08 online test: `replicas` run the base candidate argv without HiCache
    (no host L2); the other replicas are byte-identical to the base file. HiCache env vars are
    left in place: without --enable-hierarchical-cache nothing reads them."""
    src = (ROOT / SOURCE).read_text()
    out = ("# GENERATED by scripts/kvq/prepare_glm53_kvshare_ab.py --hicache-off " + ",".join(replicas) + " from "
           + str(SOURCE) + " -- do not edit by hand.\n"
           "# ONLINE TEST ARM B: " + " + ".join(replicas) + " run without HiCache (no host L2 tier); the other replicas\n"
           "# are the unchanged control (arm A). Plan: tee-bench exp 31. Deploy only those replicas, scoped.\n") + src
    cand_start = out.index("x-sg-glm53-flash-candidate: &sg-glm53-flash-candidate\n")
    cmd_start = out.index("  command: >\n      sglang serve\n", cand_start)
    cmd_end = out.index("\n\n", cmd_start)
    cmd = out[cmd_start:cmd_end]
    kept = [l for l in cmd.split("\n") if not l.strip().startswith(HICACHE_FLAGS)]
    removed = len(cmd.split("\n")) - len(kept)
    assert removed == len(HICACHE_FLAGS), f"expected {len(HICACHE_FLAGS)} HiCache flags in the candidate argv, removed {removed}"
    anchor = ("x-sg-glm53-flash-nohicache: &sg-glm53-flash-nohicache\n"
              "  # Arm B: the candidate argv above without HiCache (" + ", ".join(HICACHE_FLAGS) + ").\n"
              "  # Everything else, including the mamba slots and the environment, is the candidate's.\n"
              "  <<: *sg-glm53-flash-candidate\n" + "\n".join(kept) + "\n\n")
    out = out[:cmd_end + 2] + anchor + out[cmd_end + 2:]
    for r in replicas:
        svc = f"  model-sg-glm53-w4afp8-tp2-{r}:\n    <<: *sg-glm53-flash-candidate\n"
        out = one(out, svc, svc.replace("*sg-glm53-flash-candidate", "*sg-glm53-flash-nohicache"), f"{r} anchor")
        s0 = out.index(f"  model-sg-glm53-w4afp8-tp2-{r}:\n")
        s1 = out.index("\n  # ---", s0) if "\n  # ---" in out[s0:] else len(out)
        body = out[s0:s1].replace("-strict-budget8192-obs-v1", "-strict-budget8192-obs-v1" + OFF_SUFFIX)
        assert body.count(OFF_SUFFIX) == 2, f"{r}: expected 2 config_variant labels"
        out = out[:s0] + body + out[s1:]
    return out



