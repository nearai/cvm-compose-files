#!/usr/bin/env python3
"""Generate prod/GLM-5.3-Flash-SGL-TP2x3-W4AFP8-gpu04.yaml from prod/GLM-5.3-Flash-SGL-TP2x4-W4AFP8.yaml.

gpu04 keeps three TP2 replicas (r1-r3, GPUs 0-5); GPU 6 goes to a separate compose-manager project
(prod/sage.yaml) and GPU 7 stays idle. Text edits only, so every other byte of the base file stays as is.

Usage: python3 scripts/prepare_glm53_gpu04_tp2x3.py [--check]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "prod/GLM-5.3-Flash-SGL-TP2x4-W4AFP8.yaml"
TARGET = ROOT / "prod/GLM-5.3-Flash-SGL-TP2x3-W4AFP8-gpu04.yaml"
R4 = "model-sg-glm53-w4afp8-tp2-r4"

HEADER = """\
# gpu04 ONLY: three-replica variant of prod/GLM-5.3-Flash-SGL-TP2x4-W4AFP8.yaml, generated by
# scripts/prepare_glm53_gpu04_tp2x3.py (do not hand-edit). Replicas r1-r3 (GPUs 0-5) are byte-identical to the
# base file. Replica r4 (GPUs 6-7) is removed: GPU 6 runs the separate "sage" project (prod/sage.yaml) and GPU 7
# stays idle. Also removed with r4: its proxy backend URL, its OTel scrape job, its perception-check loop entry,
# and the soak relay's 8010 (r3) and 8011 (r4) listeners, because VM port 8010 belongs to the sage project.
# This replaces the r4 Q8 canary (prod/GLM-5.3-Flash-SGL-TP2x4-W4AFP8-Q8Canary.yaml) on gpu04.
# Never deploy a 4-replica file to gpu04 while the sage project runs: it would start r4 on GPU 6.
#
"""


def cut_block(text: str, start_marker: str, end_marker: str) -> str:
    """Remove the lines from the one holding start_marker up to (not including) the one holding end_marker."""
    s = text.index(start_marker)
    s = text.rfind("\n", 0, s) + 1
    e = text.index(end_marker, s)
    e = text.rfind("\n", 0, e) + 1
    return text[:s] + text[e:]


def transform(src: str) -> str:
    out = HEADER + src

    old = f",http://{R4}:8000\n"
    assert out.count(old) == 1, "VLLM_BACKEND_URLS r4 entry not found exactly once"
    out = out.replace(old, "\n")

    out = cut_block(
        out,
        "# --- GLM-5.3-Flash engine replica 4 (SGLang TP2, GPUs 6-7) ---",
        "# Explicit operator-only semantic check; never starts with a normal stack apply.",
    )

    old = "for replica in (1, 2, 3, 4):"
    assert out.count(old) == 1, "perception-check loop not found exactly once"
    out = out.replace(old, "for replica in (1, 2, 3):")

    for port in ("8010", "8011"):
        old = f'      - "{port}:{port}"\n'
        assert out.count(old) == 1, f"soak relay port {port} not found exactly once"
        out = out.replace(old, "")
        m = re.search(r"\n(        server \{\n          listen " + port + r" ssl;\n(?:.*\n)*?        \}\n)", out)
        assert m, f"soak relay server block {port} not found"
        out = out[: m.start(1)] + out[m.end(1):]

    out = cut_block(out, f"- job_name: sglang-{R4}", "- job_name: ghost-aggregator-glm53-ghost-aggregator")

    live = [line for line in out.splitlines() if R4 in line and not line.lstrip().startswith("#")]
    assert not live, f"live r4 references left: {live}"
    assert "device_ids: [\"6\"" not in out and "device_ids: [\"6\",\"7\"]" not in out, "GPU 6 still assigned"
    return out


def main() -> int:
    want = transform(SOURCE.read_text(encoding="utf-8"))
    if "--check" in sys.argv[1:]:
        if TARGET.read_text(encoding="utf-8") != want:
            print(f"{TARGET.relative_to(ROOT)} is stale; run scripts/prepare_glm53_gpu04_tp2x3.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(ROOT)} is up to date")
        return 0
    TARGET.write_text(want, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
